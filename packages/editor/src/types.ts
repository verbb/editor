import type { Extensions } from '@tiptap/core';

import type { EditorLabels } from './config/labels';
import type { EditorGif, GifConfig } from './gifs/giphy';

export type { EditorLabels } from './config/labels';
export type { EditorGif, GifConfig, GifRating } from './gifs/giphy';

/** `craft` maps every colour to the Control Panel's own variables. */
export type EditorTheme = 'light' | 'dark' | 'none' | 'craft';

/**
 * Controls that can sit on the toolbar. Anything enabled but not listed goes under More, with undo,
 * redo and formatting help.
 */
export type EditorTool = 'bold' | 'italic' | 'underline' | 'strike' | 'code' | 'heading' | 'bulletList' | 'orderedList' | 'blockquote' | 'link' | 'mention' | 'attach' | 'gif';

export type EditorPreset = 'minimal' | 'standard' | 'full';

export type EditorContent = Record<string, unknown>[];

export interface EditorFeatures {
    bold?: boolean;
    italic?: boolean;
    strike?: boolean;
    underline?: boolean;
    headings?: boolean | number[];
    lists?: boolean;
    blockquote?: boolean;
    code?: boolean;
    link?: boolean;
    craftLink?: boolean;
    image?: boolean;
    attachment?: boolean;
    mention?: boolean;
}

export interface CraftEndpoints {
    upload?: string;
    mentions?: string;
    elements?: string;
}

export interface CraftUploadLimits {
    imageExtensions?: string[];
    attachmentExtensions?: string[];
    maxFileSize?: number;
    /** Per document, so the editor refuses an extra file before uploading it. */
    maxImages?: number | null;
    maxAttachments?: number | null;
}

/**
 * Normally the `craft` value from `EditorConfig::browserOptions()`, which holds action URLs
 * generated by the server. Nothing here grants anything: the server checks every request.
 */
export interface CraftOptions {
    /** Trusted server context handle, e.g. comments.reply */
    context?: string;
    endpoints?: CraftEndpoints;
    csrfTokenName?: string;
    /** `false` when the site has CSRF protection turned off. */
    csrfToken?: string | false;
    /** Sent back unread for the context's `resolveScope` callable to validate. */
    scope?: Record<string, unknown>;
    uploads?: CraftUploadLimits;
    minQueryLength?: number;
}

/** Extra headers for Editor's requests: an object, or a function called before each request. */
export type EditorRequestHeaders = Record<string, string> | (() => Record<string, string> | Promise<Record<string, string>>);

/**
 * How mention, page search and upload requests are sent, for endpoints that identify the person by
 * something other than Craft's session cookie, such as a bearer token, or that live on another origin.
 */
export interface EditorRequestOptions {
    /**
     * Added to every request, such as `{ Authorization: 'Bearer …' }`. Pass a function when the value
     * changes, such as a short-lived token: it's called before each request and may return a promise.
     * Editor's own `Accept`, `Content-Type` and CSRF headers take precedence.
     */
    headers?: EditorRequestHeaders;
    /**
     * Whether requests carry cookies, as for `fetch()`. `same-origin` by default, `include` for
     * Craft's session on another origin, and `omit` for none. Uploads use `XMLHttpRequest` for
     * progress, which always sends cookies to its own origin.
     */
    credentials?: RequestCredentials;
}

export interface EditorUpdateEvent {
    editor: import('./Editor').Editor;
    json: EditorContent;
    html: string;
    text: string;
    /** The GIF going with the document, chosen from GIPHY, or null. */
    gif: EditorGif | null;
}

export interface EditorChangeEvent extends EditorUpdateEvent {
    isDirty: boolean;
}

export interface EditorUploadStateEvent {
    editor: import('./Editor').Editor;
    uploading: boolean;
    pending: number;
}

/** Where the toolbar sits relative to the text. */
export type EditorToolbarPosition = 'top' | 'bottom';

export interface EditorOptions {
    content?: EditorContent | { type: 'doc'; content: EditorContent } | string;
    theme?: EditorTheme;
    preset?: EditorPreset;
    features?: EditorFeatures;
    placeholder?: string | null;
    labels?: Partial<EditorLabels>;
    /**
     * Which enabled controls sit on the toolbar, in order. The rest go under More. `false` leaves the
     * toolbar out, for plain writing with no formatting controls.
     */
    toolbar?: EditorTool[] | false;
    /**
     * Where the toolbar sits: `bottom` (the default), just below the text, or `top`, above it. In
     * `<verbb-editor>`, a bottom toolbar shares the row with Post until the host puts something in the
     * `footer` slot, such as a form's fields; then it stays with the text and Post gets a row of its own.
     */
    toolbarPosition?: EditorToolbarPosition;
    ariaLabel?: string;
    ariaLabelledBy?: string;
    editable?: boolean;
    craft?: CraftOptions | false;
    /** Headers and credentials for the requests `craft` makes. */
    request?: EditorRequestOptions;
    /**
     * GIF search through GIPHY. With a key, the toolbar gets a GIF control, and the GIF someone
     * chooses goes with the document rather than inside it: read it with `getGif()`. Normally the
     * `gifs` value from `EditorConfig::browserOptions()`.
     */
    gifs?: GifConfig | false;
    /** The GIF the document starts with, such as an edited post's. */
    gif?: EditorGif | null;
    extensions?: Extensions;
    onUpdate?: (event: EditorUpdateEvent) => void;
    onChange?: (event: EditorChangeEvent) => void;
    onUploadState?: (event: EditorUploadStateEvent) => void;
}

export interface ResolvedEditorFeatures extends Required<EditorFeatures> {
    headings: false | number[];
}

export interface ResolvedEditorOptions {
    content: EditorContent;
    theme: EditorTheme;
    features: ResolvedEditorFeatures;
    placeholder: string;
    labels: EditorLabels;
    toolbar: EditorTool[] | false | null;
    toolbarPosition: EditorToolbarPosition;
    ariaLabel?: string;
    ariaLabelledBy?: string;
    editable: boolean;
    craft: CraftOptions | false;
    request: EditorRequestOptions;
    gifs: GifConfig | false;
    gif: EditorGif | null;
    extensions: Extensions;
    onUpdate?: (event: EditorUpdateEvent) => void;
    onChange?: (event: EditorChangeEvent) => void;
    onUploadState?: (event: EditorUploadStateEvent) => void;
}
